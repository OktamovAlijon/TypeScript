// 2. TypeScript haqida
// TypeScript JavaScript uchun superset hisoblanadi.
// JavaScript ustiga qo'shimcha imkoniyatlar beradi.
// Static typing o'zgaruvchi va parametr turini belgilaydi.
// Funksiya qaytaradigan qiymat turini ham ko'rsatish mumkin.
// Type bilan bog'liq xatolar kod yozayotganda aniqlanadi.
// Bu runtime xatolar yuzaga kelish ehtimolini kamaytiradi.
// Turlar kod sifatini yaxshilashga yordam beradi.
// IDE tavsiyalari va tekshiruvlarini qo'llab-quvvatlaydi.
// Realtime xatolarni topish dasturlashni tezlashtiradi.
// Type'lar jamoaviy ishlashda kodni tushunishni osonlashtiradi.
// JavaScript dinamik turlardan foydalanadi.
// JavaScript'da o'zgaruvchi turi bajarilish davomida aniqlanadi.
// TypeScript statik turlardan foydalanadi.
// TypeScript turlari yozish va kompilyatsiya vaqtida tekshiriladi.
// TypeScript ishlashidan oldin JavaScript'ga o'giriladi.
// JavaScript kodini brauzerlar va server muhitida ishga tushirish mumkin.
// TypeScript sintaksisi JavaScript'ga qaraganda turliroq va murakkabroq.
const courseAge: number = 25;
function displayInfo(firstName: string, lastName: string, age: number): void {
  console.log(firstName, lastName, age);
}
displayInfo('Ulugbek', 'Aliyev', courseAge);
