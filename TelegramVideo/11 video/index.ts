// 11. Linting va Formatting
// Linting kodni avtomatik tahlil qilib, xatolar haqida xabar beradi.
// U programmaga oid va stilistik muammolarni aniqlaydi.
// ESLint TypeScript uchun mashhur linting vositasidir.
// O'rnatish: npm install eslint @typescript-eslint/parser @typescript-eslint/eslint-plugin
// Sozlash buyrug'i: npx eslint --init
// ESLint parser: @typescript-eslint/parser
// TypeScript qoidalari @typescript-eslint plugin orqali qo'shiladi.
// Qoidalar sozlamada error yoki boshqa darajada belgilanadi.
// package.json ichida takroriy buyruqlarni scripts'ga yozish mumkin.
// Masalan, dev buyrug'i: tsc --watch
// Lint buyrug'i: eslint .ts
// Formatter kodni belgilangan uslubda tekislaydi.
// Prettier mashhur kod formatlovchi vositadir.
// O'rnatish: npm install --save-dev prettier
// Sozlamalar .prettierrc.json faylida yoziladi.
// Masalan, "semi": true — nuqtali vergul ishlatadi.
// "singleQuote": true — bir tirnoqli matnlarni tanlaydi.
// "arrowParens": "avoid" — kerak bo'lmaganda qavslarni qo'ymaydi.
// Ishga tushirish: npx prettier --write app.ts
// Linting kod qoidalarini tekshiradi, Prettier ko'rinishini tartiblaydi.
// Ikkalasini loyiha qoidalariga moslab sozlang.
